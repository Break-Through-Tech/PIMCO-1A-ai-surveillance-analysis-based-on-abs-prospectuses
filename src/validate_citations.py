
"""
Validate citations generated by the ABS prospectus RAG assistant.

Checks:
1. Citation numbers refer to retrieved passages.
2. Each cited passage has at least one associated deal.
3. Deal metadata includes an accession number.
4. SEC source URLs are present and belong to sec.gov.
5. The cited passage contains supporting text.

Note:
These checks validate citation integrity and provenance.
They do not independently prove that an LLM's factual claims
are logically supported by the cited text.
"""

from urllib.parse import urlparse


def validate_result(result):
    """
    Validate citations and source metadata in an answer result.

    Args:
        result: Dictionary returned by answer.answer().

    Returns:
        Dictionary containing validation status, counts, and issues.
    """

    passages = result.get("passages", [])
    cited = result.get("cited", [])
    invalid = result.get("invalid_citations", [])

    issues = []
    checked = 0
    valid = 0

    # Check citation numbers returned by the LLM.
    if invalid:
        issues.append(
            f"LLM generated invalid passage references: {invalid}"
        )

    for citation in cited:
        checked += 1

        # Check that the citation refers to a retrieved passage.
        if not isinstance(citation, int) or not 1 <= citation <= len(passages):
            issues.append(
                f"Citation [{citation}] does not refer to a retrieved passage."
            )
            continue

        passage = passages[citation - 1]
        passage_valid = True

        # Check that the passage contains actual text.
        if not passage.get("text", "").strip():
            issues.append(
                f"Citation [{citation}] has no supporting passage text."
            )
            passage_valid = False

        # Check associated deal information.
        deals = passage.get("deals", [])

        if not deals:
            issues.append(
                f"Citation [{citation}] has no associated deal."
            )
            passage_valid = False

        for deal in deals:
            accession = deal.get("accession", "")
            doc_url = deal.get("doc_url", "")

            if not accession:
                issues.append(
                    f"Citation [{citation}] has a deal with no accession number."
                )
                passage_valid = False

            if not doc_url:
                issues.append(
                    f"Citation [{citation}] has a deal with no SEC document URL."
                )
                passage_valid = False
                continue

            parsed_url = urlparse(doc_url)

            if (
                parsed_url.scheme != "https"
                or parsed_url.hostname not in ("sec.gov", "www.sec.gov")
            ):
                issues.append(
                    f"Citation [{citation}] has a URL that is not an "
                    f"HTTPS SEC.gov URL: {doc_url}"
                )
                passage_valid = False

        if passage_valid:
            valid += 1

    # A missing citation is worth flagging when passages were retrieved.
    if passages and not cited:
        issues.append(
            "The LLM retrieved passages but did not cite any of them."
        )

    return {
        "valid": len(issues) == 0,
        "checked_citations": checked,
        "valid_citations": valid,
        "issues": issues,
    }
